/**
 * historicalSectorStats.ts
 *
 * Repositorio de Series Estadísticas Históricas Semestrales de Mallorca (2006–2026).
 * Alimenta la sección /estadisticas/comparativas y las gráficas interactivas.
 * Cumple con GR-03 (TypeScript estricto), GR-04 (i18n cuatrilingüe),
 * GR-11 (Zero Fake Data: datos contrastados con IBESTAT, INE, Seguridad Social y AENA)
 * y GR-12 (delimitación geográfica insular).
 */
import type { Locale } from "../i18n";

export interface SemiannualDataPoint {
  period: string; // ej: "2006-S1", "2006-S2"
  year: number;
  semester: 1 | 2;
  value: number;
  formattedValue: string;
  note?: Record<Locale, string>;
}

export interface SectorMilestone {
  year: number;
  semester: 1 | 2;
  title: Record<Locale, string>;
  description: Record<Locale, string>;
  impactTag: "crisis" | "auge" | "normativa" | "recuperacion" | "record";
}

export type SectorTheme = "economia" | "turismo_movilidad" | "territorio" | "sociedad_bienestar";

export interface SectorHistoricalSeries {
  id: string;
  sectorKey: string;
  theme: SectorTheme;
  icon: string;
  title: Record<Locale, string>;
  shortDescription: Record<Locale, string>;
  unit: Record<Locale, string>;
  sourceEntity: string;
  officialSeriesCode: string;
  dataScope: "Mallorca" | "Illes Balears";
  dataPoints: SemiannualDataPoint[]; // De 2006-S1 a 2026-S1 (41 semestres)
  insights: {
    tenYearChangePct: number; // 2016 vs 2026
    twentyYearChangePct: number; // 2006 vs 2026
    cagr10Pct?: number; // CAGR a 10 años (%)
    cagr20Pct?: number; // CAGR a 20 años (%)
    peakSemester: string;
    peakValueFormatted: string;
    troughSemester: string;
    troughValueFormatted: string;
    summaryText: Record<Locale, string>;
  };
  milestones: SectorMilestone[];
  relatedBlogSlug: string;
  relatedCategorySlug: string;
}

