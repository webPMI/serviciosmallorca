// ─── Helpers ──────────────────────────────────────────────────────────────────

export function getSportsFacilityById(id: string): SportsFacilityPOI | undefined {
  return SPORTS_FACILITIES.find((f) => f.id === id || f.slug === id);
}

export function getSportsFacilitiesByActivity(activity: string): SportsFacilityPOI[] {
  if (!activity || activity === "all") return SPORTS_FACILITIES;
  return SPORTS_FACILITIES.filter((f) => f.activityTypes.includes(activity as any));
}

export function getSportsFacilitiesByZone(zone: string): SportsFacilityPOI[] {
  if (!zone || zone === "all") return SPORTS_FACILITIES;
  return SPORTS_FACILITIES.filter((f) => f.zone === zone);
}
